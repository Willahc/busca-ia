import {
  DISCRIMINATIVE_POWERS,
  ENTITY_RESOLUTION_ATTRIBUTES,
  type DiscriminativePower,
} from "@/intelligence/entity-resolution";
import {
  INFORMATION_GAIN_CATEGORIES,
  type InformationGainCategory,
} from "../model/evidence-assessment-model";

const ATTRIBUTE_INFORMATION_GAIN: Readonly<Record<string, InformationGainCategory>> =
  Object.freeze({
    [ENTITY_RESOLUTION_ATTRIBUTES.SEX]: INFORMATION_GAIN_CATEGORIES.LOW,
    [ENTITY_RESOLUTION_ATTRIBUTES.NATIONALITY]: INFORMATION_GAIN_CATEGORIES.LOW,
    [ENTITY_RESOLUTION_ATTRIBUTES.FULL_NAME]: INFORMATION_GAIN_CATEGORIES.MEDIUM,
    [ENTITY_RESOLUTION_ATTRIBUTES.BIRTH_DATE]: INFORMATION_GAIN_CATEGORIES.HIGH,
    [ENTITY_RESOLUTION_ATTRIBUTES.MOTHER_NAME]: INFORMATION_GAIN_CATEGORIES.HIGH,
    [ENTITY_RESOLUTION_ATTRIBUTES.FATHER_NAME]: INFORMATION_GAIN_CATEGORIES.HIGH,
    [ENTITY_RESOLUTION_ATTRIBUTES.DISTINCTIVE_MARK]: INFORMATION_GAIN_CATEGORIES.VERY_HIGH,
  });

export function informationGainForAttribute(
  attribute: string,
  fallback: DiscriminativePower
): InformationGainCategory {
  if (ATTRIBUTE_INFORMATION_GAIN[attribute]) return ATTRIBUTE_INFORMATION_GAIN[attribute];
  switch (fallback) {
    case DISCRIMINATIVE_POWERS.VERY_HIGH:
      return INFORMATION_GAIN_CATEGORIES.VERY_HIGH;
    case DISCRIMINATIVE_POWERS.HIGH:
      return INFORMATION_GAIN_CATEGORIES.HIGH;
    case DISCRIMINATIVE_POWERS.MEDIUM:
      return INFORMATION_GAIN_CATEGORIES.MEDIUM;
    default:
      return INFORMATION_GAIN_CATEGORIES.LOW;
  }
}
